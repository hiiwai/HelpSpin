"""Helpers shared by packaging/helspin.spec and packaging/helspin_macos.spec.

Kept in a plain module (not inside a spec) so it can be unit-tested on any OS.

Two things a frozen build loses and these restore:

* Package metadata. PyInstaller does not ship helspin's dist-info, so
  importlib.metadata cannot find a version inside the bundle and the window
  title and About would say "0.0.0+unknown". The spec ships a VERSION file
  next to helspin/__init__.py instead, read from pyproject at build time.

* The Windows version resource. It used to be a hand-written
  version_info.txt that stayed at 0.5.4 while the app moved on, so the
  .exe's Properties -> Details disagreed with About. It is now generated
  from the same pyproject version on every build.
"""

from __future__ import annotations

import re
from pathlib import Path

BUILD_SUBDIR = ("build", "helspin-version")
COPYRIGHT = "Copyright (c) 2026 H. Iw-ai. All rights reserved."


def read_version(root: Path) -> str:
    """The [project] version from pyproject.toml -- the single source."""
    text = (Path(root) / "pyproject.toml").read_text(encoding="utf-8")
    in_project = False
    for raw in text.splitlines():
        line = raw.split("#", 1)[0].strip()
        if line.startswith("["):
            in_project = line == "[project]"
            continue
        if not in_project:
            continue
        match = re.fullmatch(r"""version\s*=\s*["']([^"']+)["']""", line)
        if match:
            return match.group(1)
    raise SystemExit("cannot find the [project] version in pyproject.toml")


def version_tuple(version: str) -> tuple[int, int, int, int]:
    """Four 16-bit numbers for the Windows resource ("0.9.8" -> 0,9,8,0).

    Non-numeric parts ("1.0.0rc1") keep their leading digits; anything past
    the fourth component is dropped, missing ones are 0.
    """
    numbers: list[int] = []
    for piece in version.split(".")[:4]:
        match = re.match(r"\d+", piece)
        numbers.append(min(int(match.group()), 0xFFFF) if match else 0)
    while len(numbers) < 4:
        numbers.append(0)
    return (numbers[0], numbers[1], numbers[2], numbers[3])


def windows_version_info(version: str) -> str:
    """PyInstaller version-file text for HelSpin.exe."""
    four = version_tuple(version)
    safe = version.replace("'", "")
    return f"""# UTF-8
# Windows version resource embedded in HelSpin.exe (Properties -> Details).
# GENERATED by packaging/spec_support.py from pyproject.toml -- do not edit.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={four},
    prodvers={four},
    mask=0x3f, flags=0x0, OS=0x40004, fileType=0x1, subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable('040904B0', [
        StringStruct('CompanyName', 'H. Iw-ai'),
        StringStruct('FileDescription', 'HelSpin - Bruker NMR spectrum viewer'),
        StringStruct('FileVersion', '{safe}'),
        StringStruct('InternalName', 'HelSpin'),
        StringStruct('LegalCopyright', '{COPYRIGHT}'),
        StringStruct('OriginalFilename', 'HelSpin.exe'),
        StringStruct('ProductName', 'HelSpin'),
        StringStruct('ProductVersion', '{safe}')])
    ]),
    VarFileInfo([VarStruct('Translation', [1033, 1200])])
  ]
)
"""


def write_build_files(root: Path) -> tuple[str, Path, Path]:
    """Write VERSION and the Windows version file under build/.

    Returns (version, VERSION path, version_info path).
    """
    root = Path(root)
    version = read_version(root)
    out = root.joinpath(*BUILD_SUBDIR)
    out.mkdir(parents=True, exist_ok=True)
    version_file = out / "VERSION"
    version_file.write_text(version + "\n", encoding="utf-8")
    info_file = out / "version_info.txt"
    info_file.write_text(windows_version_info(version), encoding="utf-8")
    return version, version_file, info_file
